# The piers and the filtration plant: the black lines of the reference map are their roads (an outline road with cross roads), not one
# straight line through the middle. Hand-placed in map px from the reference image. Run after clean_map.py, before build_interchanges.py.
import json, os
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'chicago')
m = json.load(open(os.path.join(P, 'mapdata.json')))
m['streets'] = [s for s in m['streets'] if s.get('tag') != 'pier']
def trim(pred, x_end):      # a street that ran into the middle of a landmark now stops at the landmark's edge
    for s in m['streets']:
        if pred(s['pts']):
            p = s['pts']; xs = [q[0] for q in p]; i = xs.index(max(xs))
            if p[i][0] > x_end:
                a, b = p[i - 1], p[i]; t = (x_end - a[0]) / (b[0] - a[0]) if b[0] != a[0] else 1
                s['pts'] = p[:i] + [[round(x_end, 1), round(a[1] + (b[1] - a[1]) * t, 1)]]
trim(lambda p: abs(p[0][0] - 798) < 4 and abs(p[0][1] - 368) < 4 and p[-1][0] > 1000, 848.7)          # Navy Pier centre line
trim(lambda p: abs(p[0][0] - 761) < 4 and abs(p[0][1] - 283) < 4 and p[-1][0] > 850, 859.5)         # plant causeway
add = lambda pts: m['streets'].append({'cls': 'two', 'tag': 'pier', 'pts': [[round(x, 1), round(y, 1)] for x, y in pts]})
Y0, Y1 = 358.5, 386.7
add([(848.7, Y0), (1081, Y0), (1093, 361), (1099, 372.6), (1093, 384), (1081, Y1), (848.7, Y1)])        # outline road round the pier (top, rounded end, bottom)
for x in (848.7, 889, 945.5, 977):                                                                             # the black dividers: cross roads
    add([(x, Y0), (x, 372.6), (x, Y1)])
add([(859.5, 277.5), (960, 277.5), (960, 292.5), (960, 309), (859.5, 309), (859.5, 292.5), (859.5, 277.5)])  # ring road round the plant
json.dump(m, open(os.path.join(P, 'mapdata.json'), 'w'))
open(os.path.join(P, 'mapdata.js'), 'w').write('// generated by tools/build_mapdata.py + add_black_roads.py + add_pier_roads.py (same content as mapdata.json) - edit the map in the studio, or re-run the tools\nexport default ' + json.dumps(m) + ';\n')
print('pier roads added')
