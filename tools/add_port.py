# The container terminal: a big deck out into the lake south of the river mouth, with a road to it from the lake-shore street and a ring road round it.
# (src/port.js fills it: container stacks, hangars, gantry cranes, moored container ships and tankers.)  Run after add_pier_roads.py.
import json, os
P = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'chicago')
m = json.load(open(os.path.join(P, 'mapdata.json')))
m['decks'] = [d for d in m['decks'] if d.get('tag') != 'port']
m['streets'] = [s for s in m['streets'] if s.get('tag') != 'port']
X0, X1, Y0, Y1 = 770, 985, 596, 732            # deck, map px
m['decks'].append({'name': 'Container Terminal', 'tag': 'port', 'color': 9145227, 'pts': [[X0, Y0], [X1, Y0], [X1, Y1], [X0, Y1]]})
I = 16                                          # the ring road, inset from the deck edge
ring = [[X0 + I, Y0 + I], [X1 - I, Y0 + I], [X1 - I, Y1 - I], [X0 + I, Y1 - I], [X0 + I, Y0 + I]]
m['streets'].append({'cls': 'two', 'tag': 'port', 'pts': ring})
m['streets'].append({'cls': 'four', 'tag': 'port', 'pts': [[761.3, 715], [775, 700], [X0 + I, 688]]})      # the entry road from the shore street
m['port'] = [{'deck': 'Container Terminal'}]
json.dump(m, open(os.path.join(P, 'mapdata.json'), 'w'))
open(os.path.join(P, 'mapdata.js'), 'w').write('// generated by tools/build_mapdata.py + add_black_roads.py + add_pier_roads.py + add_port.py (same content as mapdata.json) - edit the map in the studio, or re-run the tools\nexport default ' + json.dumps(m) + ';\n')
print('port added')
