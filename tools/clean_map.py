# Sanity pass over the traced streets (map px): straighten wiggles, close gaps between dead ends and the street they point at
# (also across rivers), and drop short isolated pieces. Run after add_black_roads.py + dedupe_streets.py, before build_interchanges.py.
import json, math, os, sys
import numpy as np, cv2
H = os.path.dirname(os.path.abspath(__file__)); P = os.path.join(H, '..', 'src', 'chicago')
m = json.load(open(os.path.join(P, 'mapdata.json')))
X0, Y0 = m['origin'] if 'origin' in m else (494.5, 701.5)
S = m['streets']
EPS, SIGMA, JOIN, GAP, ISO = 1.6, 2.0, 2.8, 4.2, 45.0
def dseg(p, a, b):
    dx, dy = b[0]-a[0], b[1]-a[1]; l = dx*dx+dy*dy
    t = max(0, min(1, ((p[0]-a[0])*dx+(p[1]-a[1])*dy)/l)) if l else 0
    q = (a[0]+dx*t, a[1]+dy*t); return math.hypot(q[0]-p[0], q[1]-p[1]), q, t
def dpoly(p, pts):
    best = (1e9, None, 0)
    for i in range(len(pts)-1):
        r = dseg(p, pts[i], pts[i+1])
        if r[0] < best[0]: best = (r[0], r[1], i)
    return best
def plen(pts): return sum(math.dist(pts[i], pts[i+1]) for i in range(len(pts)-1))
def smooth(pts, step=3.0):
    pts = np.array(pts, float)
    if len(pts) < 3: return pts.tolist()
    d = np.r_[0, np.cumsum(np.hypot(*np.diff(pts, axis=0).T))]
    if d[-1] < 2*step: return [pts[0].tolist(), pts[-1].tolist()]
    n = max(2, int(d[-1]/step)+1); t = np.linspace(0, d[-1], n)
    r = np.c_[np.interp(t, d, pts[:, 0]), np.interp(t, d, pts[:, 1])]
    k = np.arange(-int(3*SIGMA), int(3*SIGMA)+1); w = np.exp(-k**2/(2*SIGMA**2)); w /= w.sum()
    pad = np.r_[np.repeat(r[:1], len(k)//2, 0), r, np.repeat(r[-1:], len(k)//2, 0)]
    sm = np.c_[np.convolve(pad[:, 0], w, 'valid'), np.convolve(pad[:, 1], w, 'valid')]
    sm[0], sm[-1] = r[0], r[-1]
    # keep real corners: where the raw line turns sharply, the raw corner point wins
    out = cv2.approxPolyDP(sm.astype(np.float32).reshape(-1, 1, 2), EPS, False).reshape(-1, 2)
    return out.tolist()
n0 = sum(len(s['pts']) for s in S)
for s in S: s['pts'] = smooth(s['pts'])
# rivers in map px
RV = [([(X0 - x/2.5, Y0 - z/2.5) for x, z in r['pts']], r['half']/2.5) for r in m['rivers']]
def in_river(p, pad=1.0): return any(dpoly(p, pl)[0] < half+pad for pl, half in RV)
def crosses_river(a, b):
    return any(in_river((a[0]+(b[0]-a[0])*t/10, a[1]+(b[1]-a[1])*t/10)) for t in range(11))
def connected(p, skip):
    return any(j != skip and dpoly(p, t['pts'])[0] < JOIN for j, t in enumerate(S))
HW = [(X0 - x/2.5 if False else x, y) for x, y in m['highway']]
def near_hw(p): return dpoly(p, HW)[0] < 30
joined = 0
for _pass in range(2):
  for i, s in enumerate(S):
    for end in (0, -1):
          pts = s['pts']; e = pts[end]
          if connected(e, i) or near_hw(e): continue
          # outward direction from the last ~10 px
          k = 1; 
          while abs(k) < len(pts) and math.dist(pts[end], pts[end + (k if end == 0 else -k)]) < 8 and k < len(pts)-1: k += 1
          o = pts[end + (k if end == 0 else -k)]
          d = np.array(e) - np.array(o); L = np.linalg.norm(d)
          if L < 0.5: continue
          d /= L; best = None
          for j, t in enumerate(S):
              if j == i: continue
              for q_ in range(len(t['pts'])-1):
                  dd, q, tt = dseg(e, t['pts'][q_], t['pts'][q_+1])
                  if dd < 0.5: continue
                  v = np.array(q) - np.array(e); ang = math.degrees(math.acos(max(-1, min(1, float(np.dot(v, d))/np.linalg.norm(v)))))
                  ok = (dd <= GAP and ang < (60 if dd > 1.5 else 90)) or (dd <= 12 and ang < 40) or (dd <= 45 and ang < 15) or (dd <= 30 and crosses_river(e, q) and ang < 35)
                  if ok and (best is None or dd < best[0] - 0.01): best = (dd, j, q_, q, tt)
          if best:
              dd, j, q_, q, tt = best; t = S[j]['pts']
              if math.dist(q, t[q_]) < 1.5: q = t[q_]
              elif math.dist(q, t[q_+1]) < 1.5: q = t[q_+1]
              else: t.insert(q_+1, list(q))
              if end == 0: pts.insert(0, list(q))
              else: pts.append(list(q))
              joined += 1
# isolated components
par = list(range(len(S)))
def f(x):
    while par[x] != x: par[x] = par[par[x]]; x = par[x]
    return x
for i, s in enumerate(S):
    for j, t in enumerate(S):
        if j <= i: continue
        if any(dpoly(p, t['pts'])[0] < JOIN for p in (s['pts'][0], s['pts'][-1])) or any(dpoly(p, s['pts'])[0] < JOIN for p in (t['pts'][0], t['pts'][-1])): par[f(i)] = f(j)
comp = {}
for i, s in enumerate(S): comp.setdefault(f(i), []).append(i)
drop = set()
for c, ids in comp.items():
    if sum(plen(S[i]['pts']) for i in ids) < ISO: drop.update(ids)
m['streets'] = [s for i, s in enumerate(S) if i not in drop]
json.dump(m, open(os.path.join(P, 'mapdata.json'), 'w'))
open(os.path.join(P, 'mapdata.js'), 'w').write('// generated by tools/build_mapdata.py (same content as mapdata.json) - edit the map in the studio, or re-run the tool\nexport default ' + json.dumps(m) + ';\n')
print('vertices', n0, '->', sum(len(s['pts']) for s in m['streets']), '| gaps closed', joined, '| dropped isolated pieces', len(drop), 'of', len(S))
