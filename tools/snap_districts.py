# Moves district rectangle edges off roads that run along them, so no road is split between two zones
# (edges only ever sit in the gaps between parallel streets). Run after regraph.py.
import json, math, os
P = os.path.join(os.path.dirname(__file__), '..', 'src', 'chicago')
md = json.load(open(os.path.join(P, 'mapdata.json')))
segs = []
for s in md['streets']:
    for a, b in zip(s['pts'], s['pts'][1:]): segs.append((a, b))
for a, b in zip(md['highway'], md['highway'][1:]): segs.append((a, b))
def pen(axis, c, lo, hi):
    # axis 'x': vertical edge x=c spanning y lo..hi; counts road length lying within 11 px of it and within 35 degrees of it
    t = 0
    for a, b in segs:
        u, v = (0, 1) if axis == 'x' else (1, 0)
        du, dv = b[u] - a[u], b[v] - a[v]; L = math.hypot(du, dv)
        if L < 1e-6: continue
        if abs(du) / L > 0.57: continue               # not running along the edge
        # portion of the segment inside the corridor |coord - c| < 11 and within lo..hi
        n = max(2, int(L / 4))
        for k in range(n):
            f = (k + .5) / n; q = (a[u] + du * f, a[v] + dv * f)
            if abs(q[0] - c) < 11 and lo <= q[1] <= hi: t += L / n
    return t
groups = {}
for d in md['districts']:
    p = d['poly']; xs = sorted({q[0] for q in p}); ys = sorted({q[1] for q in p})
    for ax, vals, other in (('x', xs, ys), ('y', ys, xs)):
        for v in vals: groups.setdefault((ax, v), []).append((other[0], other[-1]))
new = {}
for (ax, v), spans in groups.items():
    best = None
    for dc in [i * 0.5 for i in range(-80, 81)]:
        c = v + dc
        cost = sum(pen(ax, c, lo, hi) for lo, hi in spans) + abs(dc) * 0.6
        if best is None or cost < best[0]: best = (cost, c)
    new[(ax, v)] = round(best[1], 1)
    print(ax, v, '->', new[(ax, v)], 'penalty', round(sum(pen(ax, v, lo, hi) for lo, hi in spans)), '->', round(best[0]))
for d in md['districts']:
    d['poly'] = [[new[('x', q[0])], new[('y', q[1])]] for q in d['poly']]
json.dump(md, open(os.path.join(P, 'mapdata.json'), 'w'))
open(os.path.join(P, 'mapdata.js'), 'w').write('// generated by tools/apply_new_map.py + tools/regraph.py (same content as mapdata.json) - edit the map in the studio, or re-run the tools\nexport default ' + json.dumps(md) + ';\n')
