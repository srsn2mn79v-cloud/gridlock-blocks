# Drops streets that lie (almost) entirely on top of a street of the same or higher class (traced twice).
# Run after build_mapdata.py:  python3 tools/dedupe_streets.py
import json, math, os
H = os.path.dirname(os.path.abspath(__file__)); P = os.path.join(H, '..', 'src', 'chicago')
m = json.load(open(os.path.join(P, 'mapdata.json'))); S = m['streets']
rank = {'two': 0, 'four': 1, 'six': 2}
def dseg(p, a, b):
    dx, dy = b[0]-a[0], b[1]-a[1]; l = dx*dx+dy*dy
    t = max(0, min(1, ((p[0]-a[0])*dx+(p[1]-a[1])*dy)/l)) if l else 0
    return math.hypot(a[0]+dx*t-p[0], a[1]+dy*t-p[1])
dpoly = lambda p, pts: min(dseg(p, pts[i], pts[i+1]) for i in range(len(pts)-1))
def samples(pts, step=2):
    out = []
    for i in range(len(pts)-1):
        a, b = pts[i], pts[i+1]; n = max(1, int(math.hypot(b[0]-a[0], b[1]-a[1])/step))
        out += [(a[0]+(b[0]-a[0])*k/n, a[1]+(b[1]-a[1])*k/n) for k in range(n)]
    return out
drop = set()
for i, s in enumerate(S):
    sm = samples(s['pts'])
    for j, t in enumerate(S):
        if i == j or j in drop or rank[t['cls']] < rank[s['cls']] or (rank[t['cls']] == rank[s['cls']] and j < i): continue
        if sum(dpoly(p, t['pts']) < 3.2 for p in sm)/len(sm) > 0.6: drop.add(i); break
m['streets'] = [s for i, s in enumerate(S) if i not in drop]
json.dump(m, open(os.path.join(P, 'mapdata.json'), 'w'))
open(os.path.join(P, 'mapdata.js'), 'w').write('// generated by tools/build_mapdata.py (same content as mapdata.json) - edit the map in the studio, or re-run the tool\nexport default ' + json.dumps(m) + ';\n')
print('dropped', len(drop), 'of', len(S))
